【重要・地図地名の多言語化修正】

現在使用している静的ラスター画像タイル（CartoDBやOSM標準など）では、地図内の地名テキストが固定されていてユーザーの国籍・言語設定に応じて動的に変化しません。

国籍・言語選択（日本語、韓国語、英語、ドイツ語、フランス語など）に応じて、地図上の地名・国名・都市名のラベルテキストが選択した言語に即座に切り替わるように実装してください。

